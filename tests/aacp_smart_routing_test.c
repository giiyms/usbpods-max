int main(void) {
    uint8_t buf[AACP_SR_MAX_LEN];

    /* 1) Golden: hijack */
    EQ(aacp_sr_build_hijack(buf, k_peer), AACP_SR_HIJACK_LEN, "hijack len");
    EQS(buf, k_hijack, AACP_SR_HIJACK_LEN, "hijack golden");
    EQ(buf[4], 0x10, "hijack opcode");

    /* 2) Golden: media info YES/NO */
    EQ(aacp_sr_build_media_info(buf, k_self, k_peer, false), AACP_SR_MEDIA_LEN, "media NO len");
    EQS(buf, k_media_no, AACP_SR_MEDIA_LEN, "media NO golden");
    EQ(aacp_sr_build_media_info(buf, k_self, k_peer, true), AACP_SR_MEDIA_LEN, "media YES len");
    EQS(buf, k_media_yes, AACP_SR_MEDIA_LEN, "media YES golden");
    /* btName Android present */
    EQ(memcmp(buf + 6 + 6 + 2 + 3 + 10 + 1 + 22 + 1 + 18 + 1 + 3 + 1 + 9 + 1 + 17 + 6 + 1,
              "Android", 7) == 0 ? 1 : 0, 1, "btName Android in YES");

    /* 3) Golden: showUI (absolute put quirk) */
    EQ(aacp_sr_build_show_ui(buf, k_peer), AACP_SR_SHOWUI_LEN, "showUI len");
    EQS(buf, k_show_ui, AACP_SR_SHOWUI_LEN, "showUI golden");
    /* reasonHhijackv2 present */
    {
        bool found = false;
        for (size_t i = 0; i + 14 <= AACP_SR_SHOWUI_LEN; i++) {
            if (memcmp(buf + i, "reasonHhijackv2", 14) == 0) { found = true; break; }
        }
        EQ(found ? 1 : 0, 1, "reasonHhijackv2 present");
    }

    /* 4) Golden: reversed + new-device + add TiPi */
    EQ(aacp_sr_build_hijack_reversed(buf, k_peer), AACP_SR_REVERSED_LEN, "reversed len");
    EQS(buf, k_hijack_rev, AACP_SR_REVERSED_LEN, "reversed golden");
    EQ(aacp_sr_build_media_new_device(buf, k_self, k_peer), AACP_SR_MEDIA_NEW_LEN, "media_new len");
    EQS(buf, k_media_new, AACP_SR_MEDIA_NEW_LEN, "media_new golden");
    EQ(aacp_sr_build_add_tipi(buf, k_self, k_peer), AACP_SR_ADD_TIPI_LEN, "add_tipi len");
    EQS(buf, k_add_tipi, AACP_SR_ADD_TIPI_LEN, "add_tipi golden");

    /* 5) Policy: USB_IDLE → no 0x10 send; reclaim path → yes */
    EQ(aacp_sr_should_send_hijack(false, false, false), 0, "USB_IDLE no hijack");
    EQ(aacp_sr_should_send_hijack(true, false, false), 1, "USB open → hijack");
    EQ(aacp_sr_should_send_hijack(false, true, false), 1, "USB streaming → hijack");
    EQ(aacp_sr_should_send_hijack(true, true, true), 0, "anti-ping-pong blocks");
    EQ(dual_connect_should_reclaim_on_steal(true, false, false), 1, "reclaim path still on");
    /* 0x11 SetOwnershipToFalse sets we_paused_after_giveup — same gate. */
    EQ(aacp_sr_should_send_hijack(true, true, true), 0, "0x11 we_paused blocks 0x10");

    /* 6) Reclaim path builders non-empty / correct opcode */
    {
        uint8_t media[AACP_SR_MEDIA_LEN];
        uint8_t show[AACP_SR_SHOWUI_LEN];
        uint8_t hij[AACP_SR_HIJACK_LEN];
        size_t nm = aacp_sr_build_media_info(media, k_self, k_peer, true);
        size_t ns = aacp_sr_build_show_ui(show, k_peer);
        size_t nh = aacp_sr_build_hijack(hij, k_peer);
        EQ(nm > 0 && ns > 0 && nh > 0 ? 1 : 0, 1, "reclaim builders non-empty");
        EQ(media[4], 0x10, "media opcode 0x10");
        EQ(show[4], 0x10, "showUI opcode 0x10");
        EQ(hij[4], 0x10, "hijack opcode 0x10");
        /* peer MAC LE-reversed at start of buffer */
        EQ(hij[6], 0xFF, "hijack mac[0] rev");
        EQ(hij[11], 0xAA, "hijack mac[5] rev");
    }

    /* 7) MAC ASCII helper */
    {
        char a[18];
        aacp_sr_mac_to_ascii(k_self, a);
        EQS(a, "11:22:33:44:55:66", 17, "mac ascii");
    }

    printf("aacp_smart_routing_test: PASS "
           "(hijack, media YES/NO, showUI, reversed, media_new, add_tipi, "
           "USB_IDLE gate, reclaim builders)\n");
    return 0;
}
