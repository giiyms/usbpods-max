#define EQ(a, b, msg) do { if ((unsigned)(a) != (unsigned)(b)) { \
    fprintf(stderr, "FAIL: %s (%u != %u)\n", msg, (unsigned)(a), (unsigned)(b)); \
    exit(1); } } while (0)

#define EQS(a, b, n, msg) do { if (memcmp((a), (b), (n)) != 0) { \
    fprintf(stderr, "FAIL: %s\n", msg); \
    const uint8_t *_a = (const uint8_t *)(a), *_b = (const uint8_t *)(b); \
    for (size_t _i = 0; _i < (size_t)(n); _i++) { \
        if (_a[_i] != _b[_i]) { \
            fprintf(stderr, "  first diff @%zu: got %02X want %02X\n", _i, _a[_i], _b[_i]); \
            break; \
        } \
    } \
    exit(1); } } while (0)

